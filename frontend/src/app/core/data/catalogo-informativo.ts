export function obtenerCategoria(slug: string): CategoriaInformativa | undefined {
  return CATEGORIAS_INFORMATIVAS.find((categoria) => categoria.slug === slug);
}

export function productosPorCategoria(slug: string): readonly ProductoInformativo[] {
  return PRODUCTOS_INFORMATIVOS.filter((producto) => producto.categoriaSlug === slug);
}

export function obtenerProducto(
  categoriaSlug: string,
  productoSlug: string,
): ProductoInformativo | undefined {
  return PRODUCTOS_INFORMATIVOS.find(
    (producto) => producto.categoriaSlug === categoriaSlug && producto.slug === productoSlug,
  );
}

/** Hasta seis productos de la misma categoría, excluido el actual. */
export function productosRelacionados(producto: ProductoInformativo): readonly ProductoInformativo[] {
  return productosPorCategoria(producto.categoriaSlug)
    .filter((candidato) => candidato.slug !== producto.slug)
    .slice(0, 6);
}

